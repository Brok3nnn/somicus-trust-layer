//! The R-suite: evaluation harnesses for the Somicus Privacy Shield, run against the public API of `somicus-privacy`.
//!
//! R-suite v0 (this module): checksum IDs ≥ 99%, names ≥ 90%, ≤ 40 ms p95 on DE/EN/HU synthetic screens.
//! R-suite v1 ([`v1`]): recall and precision on
//! labelled synthetic English screens, and the time per screen.
//!
//! It lives under `evals/` so that no shipped crate carries an evaluation harness or a wall-clock benchmark.

#![forbid(unsafe_code)]

pub mod dataset;
pub mod v1;

use dataset::{LabeledSample, de_samples, en_samples, hu_samples};
use somicus_privacy::PrivacyShield;
use somicus_uigraph::fingerprint::ElementFingerprint;
use somicus_uigraph::geometry::PhysicalRect;
use somicus_uigraph::graph::{AppInfo, DisplayInfo, FocusInfo, UiGraph, WindowInfo};
use somicus_uigraph::node::{
    NodeActions, NodeId, NodeRelations, NodeSource, NodeStates, SelectorSet, UiNode,
};
use somicus_uigraph::privacy::{ClassifiedText, PrivacyClass};
use somicus_uigraph::role::Role;
use std::time::Instant;

/// Detailed evaluation report generated by running R-suite v0.
#[derive(Debug, Clone, PartialEq)]
pub struct RSuiteReport {
    /// Checksum identifier recall for German (DE) screens (0.0 to 1.0).
    pub de_checksum_recall: f64,
    /// Checksum identifier recall for English (EN) screens (0.0 to 1.0).
    pub en_checksum_recall: f64,
    /// Checksum identifier recall for Hungarian (HU) screens (0.0 to 1.0).
    pub hu_checksum_recall: f64,
    /// Overall checksum identifier recall across all languages (0.0 to 1.0).
    pub overall_checksum_recall: f64,
    /// Personal name recall for German (DE) screens (0.0 to 1.0).
    pub de_name_recall: f64,
    /// Personal name recall for English (EN) screens (0.0 to 1.0).
    pub en_name_recall: f64,
    /// Personal name recall for Hungarian (HU) screens (0.0 to 1.0).
    pub hu_name_recall: f64,
    /// Overall personal name recall across all languages (0.0 to 1.0).
    pub overall_name_recall: f64,
    /// Median (p50) redaction latency on 2,000-node screens in milliseconds.
    pub latency_p50_ms: f64,
    /// 95th percentile (p95) redaction latency on 2,000-node screens in milliseconds.
    pub latency_p95_ms: f64,
    /// Whether all R-suite v0 thresholds passed.
    pub all_passed: bool,
}

/// Runs the R-suite v0 evaluation and latency benchmark.
#[must_use]
pub fn run_r_suite() -> RSuiteReport {
    let mut shield = PrivacyShield::new();

    let de = de_samples();
    let en = en_samples();
    let hu = hu_samples();

    let (de_chk, de_name) = eval_samples(&mut shield, &de);
    let (en_chk, en_name) = eval_samples(&mut shield, &en);
    let (hu_chk, hu_name) = eval_samples(&mut shield, &hu);

    let total_chk_samples = de_chk.1 + en_chk.1 + hu_chk.1;
    let total_chk_detected = de_chk.0 + en_chk.0 + hu_chk.0;
    let overall_checksum_recall = if total_chk_samples > 0 {
        f64::from(total_chk_detected) / f64::from(total_chk_samples)
    } else {
        1.0
    };

    let total_name_samples = de_name.1 + en_name.1 + hu_name.1;
    let total_name_detected = de_name.0 + en_name.0 + hu_name.0;
    let overall_name_recall = if total_name_samples > 0 {
        f64::from(total_name_detected) / f64::from(total_name_samples)
    } else {
        1.0
    };

    // Benchmark on synthetic 2,000-node screen
    let (p50_ms, p95_ms) = benchmark_redaction_latency(&mut shield, 20);

    let latency_target = if cfg!(debug_assertions) { 60.0 } else { 40.0 };
    let all_passed =
        overall_checksum_recall >= 0.99 && overall_name_recall >= 0.90 && p95_ms <= latency_target;

    RSuiteReport {
        de_checksum_recall: safe_ratio(de_chk.0, de_chk.1),
        en_checksum_recall: safe_ratio(en_chk.0, en_chk.1),
        hu_checksum_recall: safe_ratio(hu_chk.0, hu_chk.1),
        overall_checksum_recall,
        de_name_recall: safe_ratio(de_name.0, de_name.1),
        en_name_recall: safe_ratio(en_name.0, en_name.1),
        hu_name_recall: safe_ratio(hu_name.0, hu_name.1),
        overall_name_recall,
        latency_p50_ms: p50_ms,
        latency_p95_ms: p95_ms,
        all_passed,
    }
}

fn safe_ratio(num: u32, denom: u32) -> f64 {
    if denom > 0 {
        f64::from(num) / f64::from(denom)
    } else {
        1.0
    }
}

fn eval_samples(shield: &mut PrivacyShield, samples: &[LabeledSample]) -> ((u32, u32), (u32, u32)) {
    let mut chk_detected = 0u32;
    let mut chk_total = 0u32;
    let mut name_detected = 0u32;
    let mut name_total = 0u32;

    for s in samples {
        let input = ClassifiedText::public_label(s.text);
        let redacted = shield.redact_text(&input);
        let redacted_str = redacted.as_inner();

        // Entity is successfully redacted if raw text was removed and a pseudonym token was inserted
        let removed_raw = !redacted_str.contains(s.expected_raw);
        let has_token = redacted_str.contains('⟦') && redacted_str.contains('⟧');
        let success = removed_raw && has_token;

        if s.is_checksum_id {
            chk_total += 1;
            if success {
                chk_detected += 1;
            }
        } else {
            name_total += 1;
            if success {
                name_detected += 1;
            }
        }
    }

    ((chk_detected, chk_total), (name_detected, name_total))
}

fn benchmark_redaction_latency(shield: &mut PrivacyShield, runs: usize) -> (f64, f64) {
    let synthetic_screen = build_synthetic_2000_node_graph();
    // Warm up compiled pattern recognizers before measuring steady-state per-screen latency.
    let _ = shield.redact_uigraph(&synthetic_screen);
    let mut durations_ms = Vec::with_capacity(runs);

    for _ in 0..runs {
        let start = Instant::now();
        let _ = shield.redact_uigraph(&synthetic_screen);
        let elapsed = start.elapsed();
        durations_ms.push(elapsed.as_secs_f64() * 1000.0);
    }

    durations_ms.sort_by(|a, b| a.partial_cmp(b).unwrap_or(std::cmp::Ordering::Equal));

    let p50_idx = (durations_ms.len() * 50) / 100;
    let p95_idx = ((durations_ms.len() * 95) / 100).min(durations_ms.len() - 1);

    (durations_ms[p50_idx], durations_ms[p95_idx])
}

fn build_synthetic_2000_node_graph() -> UiGraph {
    let display = DisplayInfo {
        display_id: 1,
        bounds_px: PhysicalRect::new(0, 0, 1920, 1080),
        scale_factor: 1.0,
        work_area_px: PhysicalRect::new(0, 0, 1920, 1040),
        is_primary: true,
    };

    let app = AppInfo {
        app_ref: "app_1".to_string(),
        app_id: Some("enterprise_portal".to_string()),
        process_name: "portal.exe".to_string(),
        bundle_id: None,
        exe_path: None,
        version: Some("1.0.0".to_string()),
        pid: 1000,
    };

    let window = WindowInfo {
        window_ref: "win_1".to_string(),
        app_ref: "app_1".to_string(),
        title: ClassifiedText::public_label("Enterprise Portal - Records"),
        bounds_px: PhysicalRect::new(0, 0, 1920, 1080),
        display_id: 1,
        z_order: 0,
        is_foreground: true,
        is_modal: false,
        url: None,
    };

    let mut nodes = Vec::with_capacity(2000);
    for i in 0..2000u64 {
        let (name, val) = match i % 5 {
            0 => (
                format!("Customer #{i}"),
                Some(format!("alice.{i}@company.example")),
            ),
            1 => (
                format!("Account #{i}"),
                Some("DE89370400440532013000".to_string()),
            ),
            2 => (format!("Employee #{i}"), Some("Thomas Schmidt".to_string())),
            3 => (format!("Phone #{i}"), Some("+49 30 1234567".to_string())),
            _ => (format!("Field #{i}"), Some(format!("Value #{i}"))),
        };

        let i_i32 = i32::try_from(i).unwrap_or(0);
        nodes.push(UiNode {
            id: NodeId::new(format!("node_{i}")),
            fp: ElementFingerprint::new(i),
            parent: None,
            children: Vec::new(),
            role: Role::Label,
            name: ClassifiedText::public_label(name),
            description: None,
            value: val.map(ClassifiedText::content_value),
            states: NodeStates::default(),
            bounds: Some(PhysicalRect::new(
                (i_i32 % 50) * 30,
                (i_i32 / 50) * 25,
                120,
                20,
            )),
            actions: NodeActions::default(),
            shortcut: None,
            relations: NodeRelations::default(),
            source: NodeSource::Uia,
            selectors: SelectorSet::default(),
            confidence: 0.90,
            classification: PrivacyClass::PublicLabel,
        });
    }

    UiGraph {
        snapshot_id: "synthetic-2000".to_string(),
        captured_at_unix_ms: 1_700_000_000_000,
        base_snapshot_id: None,
        displays: vec![display],
        apps: vec![app],
        windows: vec![window],
        focus: FocusInfo::default(),
        nodes,
    }
}
